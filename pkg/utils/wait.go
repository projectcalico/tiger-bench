package utils

import (
	"context"
	"time"
)

// SleepCtx waits for d, or until ctx is done, whichever comes first. A non-positive d
// returns immediately, as time.Sleep does - pacing loops that have fallen behind schedule
// rely on that.
func SleepCtx(ctx context.Context, d time.Duration) error {
	if d <= 0 {
		return ctx.Err()
	}
	timer := time.NewTimer(d)
	defer timer.Stop()
	select {
	case <-ctx.Done():
		return ctx.Err()
	case <-timer.C:
		return nil
	}
}
